#!/usr/bin/env python3
"""Build the Italian page (it/index.html) from index-v4.html.

index-v4.html is the only page you edit: every translatable element already
carries its Italian text in data-it (data-it-aria for labels, data-it-label for
dropdown groups, data-fill-it for the scroll statement). This script writes
those texts into the HTML so search engines index a real Italian page at /it/.

Run it after every change to index-v4.html, before committing:
    python3 tools/build-it.py
"""
import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://italiantechlandscape.com"
src = (ROOT / "index-v4.html").read_text(encoding="utf-8")
s = src


def attr(tag, name):
    m = re.search(r'\s' + re.escape(name) + r'="([^"]*)"', tag)
    return m.group(1) if m else None


def set_attr(tag, name, value):
    if re.search(r'\s' + re.escape(name) + r'="', tag):
        return re.sub(r'(\s' + re.escape(name) + r'=")[^"]*(")', lambda m: m.group(1) + value + m.group(2), tag, count=1)
    return tag[:-1] + f' {name}="{value}">'


# 1. Text content: <tag ... data-it="X">text</tag>  ->  X
def text_swap(m):
    open_tag, name, _, close = m.group(1), m.group(2), m.group(3), m.group(4)
    return open_tag + attr(open_tag, "data-it") + close

s, n_text = re.subn(r'(<(\w+)\b[^>]*\sdata-it="[^"]*"[^>]*>)([^<]*)(</\2>)', text_swap, s)

# 2. Attributes: meta content, aria-label, optgroup label, the scroll statement
def tag_swap(m):
    tag = m.group(0)
    it = attr(tag, "data-it")
    if tag.startswith("<meta") and it is not None:
        tag = set_attr(tag, "content", it)
    if attr(tag, "data-it-aria") is not None:
        tag = set_attr(tag, "aria-label", attr(tag, "data-it-aria"))
    if attr(tag, "data-it-label") is not None:
        tag = set_attr(tag, "label", attr(tag, "data-it-label"))
    return tag

s = re.sub(r'<\w+\b[^>]*\sdata-it(?:-aria|-label)?="[^"]*"[^>]*>', tag_swap, s)
s = re.sub(r'(<p class="band-title"[^>]*data-chars-it="([^"]*)"[^>]*>)[^<]*(</p>)', lambda m: m.group(1) + m.group(2) + m.group(3), s)
s = re.sub(r'(<p class="fill"[^>]*data-fill-it="([^"]*)"[^>]*>)[^<]*(</p>)',
           lambda m: m.group(1) + m.group(2).replace("*", "") + m.group(3), s)

# 3. Page-level: language, title, canonical, social tags
TITLE_IT = "Italian Tech Landscape 2026 · Il report ufficiale del Tech Made in Italy"
desc_it = re.search(r'<meta name="description"[^>]*data-it="([^"]*)"', src).group(1)
s = s.replace('<html lang="en">', '<html lang="it">', 1)
s = re.sub(r"<title>[^<]*</title>", f"<title>{TITLE_IT}</title>", s, count=1)
s = s.replace(f'<link rel="canonical" href="{SITE}/">', f'<link rel="canonical" href="{SITE}/it/">')
s = s.replace(f'<meta property="og:url" content="{SITE}/">', f'<meta property="og:url" content="{SITE}/it/">')
s = s.replace('<meta property="og:locale" content="en_GB">', '<meta property="og:locale" content="it_IT">')
s = s.replace('<meta property="og:locale:alternate" content="it_IT">', '<meta property="og:locale:alternate" content="en_GB">')
s = re.sub(r'(<meta property="og:title" content=")[^"]*', lambda m: m.group(1) + TITLE_IT, s)
s = re.sub(r'(<meta property="og:description" content=")[^"]*', lambda m: m.group(1) + desc_it, s)
s = s.replace("/assets/og/og-en.jpg", "/assets/og/og-it.jpg")
s = s.replace('<meta property="og:image:alt" content="Italian Tech Landscape 2026 report cover">',
              '<meta property="og:image:alt" content="Copertina del report Italian Tech Landscape 2026">')
s = s.replace('data-set-lang="en" aria-pressed="true"', 'data-set-lang="en" aria-pressed="false"')
s = s.replace('data-set-lang="it" aria-pressed="false"', 'data-set-lang="it" aria-pressed="true"')

# 4. The page lives one folder down: make local file paths absolute
s = re.sub(r'(\s(?:src|href|poster)=")(assets/)', r"\1/\2", s)

out = ROOT / "it" / "index.html"
out.parent.mkdir(exist_ok=True)
out.write_text("<!-- Generated by tools/build-it.py from index-v4.html. Do not edit by hand. -->\n" + s, encoding="utf-8")
left = len(re.findall(r'(<(\w+)\b[^>]*\sdata-it="([^"]*)"[^>]*>)([^<]*)(</\2>)', s))
print(f"it/index.html written: {n_text} texts translated")
