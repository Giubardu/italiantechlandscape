#!/usr/bin/env python3
"""Build the Italian test landing (ita/index.html) from it/index.html.

/ita/ is a second Italian page used to test the marketer's changes (Nov 2026) against /it/,
which stays as it is. It is generated, so every later change to index-v4.html reaches it too.
Each change below must match exactly once: if an edit to index-v4.html moves one of these
spots, the build stops and names it instead of publishing a half-changed page.

build-it.py runs this at the end, so the usual loop does not change:
    python3 tools/build-it.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://italiantechlandscape.com"
src = (ROOT / "it" / "index.html").read_text(encoding="utf-8")
s = src.split("\n", 1)[1]  # drop the "Generated by build-it.py" line


def once(pattern, repl, name, count=1):
    global s
    s, n = re.subn(pattern, repl, s, flags=re.S)
    if n != count:
        raise SystemExit(f"build-ita: '{name}' matched {n} times, expected {count}. Check index-v4.html.")


# ---- Page level: own URL, Italian only, kept out of search results (it duplicates /it/) ----
once(r'<html lang="it">', '<html lang="it" data-variant="ita">', "html tag")
once(r'<meta name="robots" content="[^"]*">', '<meta name="robots" content="noindex, follow">', "robots")
once(re.escape(f'<link rel="canonical" href="{SITE}/it/">'), f'<link rel="canonical" href="{SITE}/ita/">', "canonical")
once(r'\s*<link rel="alternate" hreflang="[^"]*" href="[^"]*">', "", "hreflang", count=3)
once(re.escape(f'<meta property="og:url" content="{SITE}/it/">'), f'<meta property="og:url" content="{SITE}/ita/">', "og:url")
once(r'\s*<div class="lang" role="group".*?</div>', "", "language switch")

# ---- 1. Hero: subtitle, two buttons, line under them ----
once(r'<p class="lede after after-1"[^>]*>[^<]*</p>',
     '<p class="lede after after-1">669 aziende e 1.652 soluzioni tecnologiche sviluppate in Italia, verificate sui registri ufficiali e validate con le aziende stesse. Scarica gratis l’edizione 2026.</p>',
     "hero subtitle")
once(r'<div class="hero-actions after after-2">.*?</div>',
     '<div class="hero-actions after after-2">\n'
     '        <button type="button" class="btn btn-accent" data-open-gate><span>Scarica gratis il report</span> <span class="arrow" aria-hidden="true">→</span></button>\n'
     '        <a class="btn btn-ghost" href="#event" data-to-ticket><span>Pass per il 24 febbraio · 99 €</span></a>\n'
     '      </div>\n'
     '      <p class="cta-micro hero-micro after after-2">Milano, Monterosa 91 · 24 febbraio 2027 · la 4ª edizione presentata in anteprima</p>',
     "hero buttons")

# ---- 2. Mobile bar: two buttons side by side ----
once(r'<div class="mbar" id="mbar">.*?</div>',
     '<div class="mbar" id="mbar">\n'
     '  <button type="button" class="btn btn-primary" data-open-gate><span>Report gratis</span></button>\n'
     '  <a class="btn btn-accent" href="#ticket" data-to-ticket><span>Pass · 99 €</span></a>\n'
     '</div>',
     "mobile bar")

# ---- 3. Button at the end of "Un report basato sui dati" ----
once(r'(<section class="section deep" id="findings".*?</ul>)',
     r'\1' + '\n'
     '    <div class="findings-cta rv">\n'
     '      <button type="button" class="btn btn-accent" data-open-gate><span>Scarica il report completo</span> <span class="arrow" aria-hidden="true">→</span></button>\n'
     '      <p class="cta-micro">Gratis · 669 aziende, 1.652 soluzioni, 389 città</p>\n'
     '    </div>',
     "findings button")

# ---- 4. Report form: new intro (fields unchanged) ----
once(r'<p class="gate-note">.*?</p>',
     '<p class="gate-note">Ricevi il report completo via email, gratis. <strong>Usa la tua email aziendale</strong> (no Gmail, Yahoo, Outlook o info@): il nostro team verifica ogni richiesta prima dell’invio.</p>',
     "form intro")

# ---- 5. After sending: pass box under the thank-you ----
once(r'(<div class="gate-done" id="report-done".*?)(<button type="button" class="btn btn-ghost" data-close>)',
     r'\1' + '<div class="done-pass">\n'
     '        <p class="done-pass-title">Vuoi vedere la 4ª edizione prima di tutti?</p>\n'
     '        <p>La presentiamo il 24 febbraio 2027 al Monterosa 91 di Milano. Il pass da 99 € include le sessioni, il pranzo executive e il networking serale.</p>\n'
     '        <a class="btn btn-accent" href="#event" data-to-ticket><span>Acquista il tuo Pass</span> <span class="arrow" aria-hidden="true">→</span></a>\n'
     '      </div>\n'
     '      ' + r'\2',
     "pass box")

# ---- 8. No partner section, no Partner links (the partner kit PDF stays on the server) ----
once(r'<!-- =+ PARTNERS =+ -->.*?(?=<!-- =+ REGISTER)', "", "partners section")
once(r'\s*<a href="#partners"[^>]*>[^<]*</a>', "", "partner links", count=2)

# ---- Styles for the new pieces ----
CSS = """
    /* /ita/ test landing (tools/build-ita.py) */
    [data-variant="ita"] .hero-actions { flex-direction: row; flex-wrap: wrap; align-items: center; }
    [data-variant="ita"] .hero-micro { margin-top: -14px; }
    .findings-cta { display: grid; justify-items: center; gap: 14px; margin-top: clamp(40px, 6vw, 72px); text-align: center; }
    .done-pass { display: grid; gap: 12px; justify-items: start; width: 100%; padding: 22px; border: 1px solid var(--accent); border-radius: 16px; background: rgba(62, 209, 209, .06); }
    .done-pass p { margin: 0; font-size: .92rem; line-height: 1.6; color: var(--on-ink-muted); }
    .done-pass .done-pass-title { font: 700 1.05rem/1.35 var(--font); color: var(--white); }
    .done-pass .btn { margin-top: 4px; }
    @media (max-width: 720px) {
      [data-variant="ita"] .hero-actions { flex-direction: column; align-items: stretch; }
    }
    @media (max-width: 960px) {
      [data-variant="ita"] .mbar { grid-template-columns: repeat(2, minmax(0, 1fr)); }
    }
  </style>"""
once(r'\n  </style>', CSS, "style block")

for left in ("#partners", 'id="partner-form"', "data-set-lang"):
    if left in s:
        raise SystemExit(f"build-ita: '{left}' is still in the page.")

out = ROOT / "ita" / "index.html"
out.parent.mkdir(exist_ok=True)
out.write_text("<!-- Generated by tools/build-ita.py from it/index.html. Do not edit by hand. -->\n" + s, encoding="utf-8")
print(f"Wrote {out.relative_to(ROOT)}")
